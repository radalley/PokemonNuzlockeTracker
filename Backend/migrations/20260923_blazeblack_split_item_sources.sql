WITH modes AS (
    SELECT split_key, item_name,
        CASE
            WHEN bool_or(method_kind = 'conditional') THEN 'Conditional'
            WHEN bool_or(method_kind = 'thief') AND bool_or(method_kind = 'dust_cloud') THEN 'Multiple sources'
            WHEN bool_or(method_kind = 'dust_cloud') THEN 'Dust cloud'
            ELSE 'Thief'
        END AS method
    FROM _bb_split_sources GROUP BY split_key, item_name
)
INSERT INTO curated_split_items(game_id, split_key, item_name, method)
SELECT 1001, modes.split_key, modes.item_name, modes.method FROM modes
WHERE EXISTS (SELECT 1 FROM games WHERE game_id = 1001)
AND NOT EXISTS (
    SELECT 1 FROM curated_split_items item
    WHERE item.game_id = 1001 AND item.split_key = modes.split_key AND item.item_name = modes.item_name
);

INSERT INTO curated_split_item_sources(
    item_record_id, source_key, method_kind, source_species_id,
    chance_percent, source_detail, source_url, sort_order
)
SELECT item.item_record_id, src.source_key, src.method_kind, src.species_id,
       src.chance, src.detail, src.source_url, src.sort_order
FROM _bb_split_sources src
JOIN LATERAL (
    SELECT item_record_id FROM curated_split_items
    WHERE game_id = 1001 AND split_key = src.split_key AND item_name = src.item_name
    ORDER BY item_record_id LIMIT 1
) item ON true
ON CONFLICT (item_record_id, source_key) DO UPDATE SET
    method_kind = excluded.method_kind,
    source_species_id = excluded.source_species_id,
    chance_percent = excluded.chance_percent,
    source_detail = excluded.source_detail,
    source_url = excluded.source_url,
    sort_order = excluded.sort_order;

