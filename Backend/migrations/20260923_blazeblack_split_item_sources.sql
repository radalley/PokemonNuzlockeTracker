-- Structured provenance for split items plus the initial Blaze Black early-game catalogue.
BEGIN;
SELECT pg_advisory_xact_lock(hashtext('lockley:blazeblack_split_item_sources_v1'));
CREATE TABLE IF NOT EXISTS schema_migrations (
    migration_name text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT current_timestamp
);
CREATE TABLE IF NOT EXISTS curated_split_item_sources (
    item_source_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_record_id bigint NOT NULL REFERENCES curated_split_items(item_record_id) ON DELETE CASCADE,
    source_key text NOT NULL CHECK (length(source_key) BETWEEN 1 AND 160),
    method_kind text NOT NULL CHECK (method_kind IN ('thief', 'dust_cloud', 'conditional', 'manual')),
    source_species_id integer,
    chance_percent numeric(5,2) CHECK (chance_percent IS NULL OR chance_percent BETWEEN 0 AND 100),
    source_detail text,
    source_url text,
    sort_order integer NOT NULL DEFAULT 0,
    UNIQUE (item_record_id, source_key)
);
CREATE INDEX IF NOT EXISTS curated_split_item_sources_item_idx
    ON curated_split_item_sources(item_record_id, sort_order);
ALTER TABLE curated_split_item_sources ENABLE ROW LEVEL SECURITY;

-- Preserve items entered through the original split/item/method editor.
INSERT INTO curated_split_item_sources(item_record_id, source_key, method_kind, source_detail)
SELECT item_record_id, 'manual:legacy', 'manual', method
FROM curated_split_items item
WHERE NOT EXISTS (
    SELECT 1 FROM curated_split_item_sources src WHERE src.item_record_id = item.item_record_id
)
AND NOT EXISTS (
    SELECT 1 FROM schema_migrations WHERE migration_name = 'blazeblack_split_item_sources_v1'
);

CREATE TEMP TABLE _bb_split_sources (
    split_key text, item_name text, source_key text, method_kind text,
    species_id integer, chance numeric(5,2), detail text, source_url text, sort_order integer
) ON COMMIT DROP;

